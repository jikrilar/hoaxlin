<?php

namespace Tests\Feature;

use App\Filament\Resources\ModelVersions\ModelVersionResource;
use App\Filament\Resources\ModelVersions\Pages\ListModelVersions;
use App\Filament\Resources\ModelVersions\Pages\ViewModelVersion;
use App\Filament\Support\AdminGlossary;
use App\Models\ModelVersion;
use App\Models\User;
use App\Services\Bert\BertCsvValidator;
use App\Services\Bert\BertTrainingService;
use Filament\Actions\Action;
use Filament\Actions\ActionGroup;
use Filament\Actions\CreateAction;
use Filament\Facades\Filament;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Http;
use Livewire\Livewire;
use Tests\TestCase;

/** T3.8: a compact model-version table, plain-language notices, and a CSV template. */
class AdminModelVersionClarityTest extends TestCase
{
    use RefreshDatabase;

    protected function setUp(): void
    {
        parent::setUp();
        Filament::setCurrentPanel(Filament::getPanel('admin'));
        Http::preventStrayRequests();
    }

    public function test_default_columns_are_the_six_summary_fields_and_the_rest_start_hidden(): void
    {
        $this->admin();
        $table = Livewire::test(ListModelVersions::class)->instance()->getTable();

        $this->assertSame(
            ['version_name', 'status', 'accuracy', 'baseline_accuracy', 'is_active', 'created_at'],
            array_keys($table->getVisibleColumns()),
        );

        foreach (['total_rows', 'f1_score', 'training_duration'] as $column) {
            $this->assertTrue($table->getColumn($column)->isToggleable(), "{$column} can be toggled back on");
            $this->assertTrue($table->getColumn($column)->isToggledHiddenByDefault(), "{$column} starts hidden");
        }
    }

    public function test_every_metric_and_state_column_explains_its_term(): void
    {
        $this->admin();
        $table = Livewire::test(ListModelVersions::class)->instance()->getTable();

        $this->assertSame(AdminGlossary::explain('accuracy'), $table->getColumn('accuracy')->getTooltip());
        $this->assertSame(AdminGlossary::explain('f1_score'), $table->getColumn('f1_score')->getTooltip());
        $this->assertSame(AdminGlossary::explain('baseline_comparison'), $table->getColumn('baseline_accuracy')->getTooltip());
        $this->assertSame(AdminGlossary::explain('active_inference_status'), $table->getColumn('is_active')->getTooltip());
        $this->assertSame(AdminGlossary::explain('model_status'), $table->getColumn('status')->getTooltip());

        foreach (['accuracy', 'f1_score', 'baseline_comparison', 'active_inference_status', 'model_status'] as $term) {
            $this->assertNotSame(AdminGlossary::NOT_AVAILABLE, AdminGlossary::explain($term), "{$term} needs a real explanation");
        }
    }

    public function test_training_notice_stays_plain_but_accurate(): void
    {
        $notice = ModelVersionResource::TRAINING_NOTICE;

        foreach (['incremental fine-tuning', 'hot-swap', 'provenance', 'classifier'] as $jargon) {
            $this->assertStringNotContainsString($jargon, $notice);
        }
        $this->assertStringContainsString('tidak otomatis', $notice);
        $this->assertStringContainsString('model aktif', $notice);
        $this->assertStringContainsString('manual', $notice);
        $this->assertStringContainsString('dihapus', $notice, 'the notice must say existing versions are not deleted');
    }

    public function test_baseline_action_moves_into_an_overflow_group_behind_train(): void
    {
        $this->admin();
        $actions = $this->headerActions();

        // The page returns a list: one primary action, then one overflow trigger.
        $this->assertCount(2, $actions);
        $this->assertInstanceOf(CreateAction::class, $actions[0]);
        $this->assertSame('Latih Versi Baru', $actions[0]->getLabel());
        $this->assertInstanceOf(ActionGroup::class, $actions[1], 'secondary actions live behind one overflow trigger');
        $this->assertArrayHasKey('activateBaseline', $actions[1]->getFlatActions());
        $this->assertSame('Aksi lain', $actions[1]->getLabel());
    }

    public function test_activation_modal_warns_that_internal_metrics_do_not_guarantee_new_data(): void
    {
        $this->admin();
        $completed = ModelVersion::factory()->completed()->create(['version_name' => 'v1.9.0']);

        // The modal text is generated by the action; asserting the mounted modal
        // needs the record-key context that `assertTableActionMounted` does not expect.
        Livewire::test(ListModelVersions::class)->mountTableAction('activate', $completed);
        $this->assertTrue($completed->exists);

        $description = ModelVersionResource::activationDescription('v1.9.0', '+3.25% (94.25% vs baseline 91.00%)');

        $this->assertStringContainsString('data validasi internal', $description);
        $this->assertStringContainsString('tidak menjamin kualitas pada data baru', $description);
        $this->assertStringContainsString('evaluasi', $description);
        $this->assertStringContainsString('sebelum', $description);
        $this->assertStringContainsString('+3.25%', $description);
    }

    public function test_baseline_activation_modal_uses_the_same_warning(): void
    {
        $this->admin();
        $action = $this->headerActions()[1]->getFlatActions()['activateBaseline'];

        $description = $action->getModalDescription();

        $this->assertStringContainsString('baseline v1.0.0', $description);
        $this->assertStringContainsString('tidak dihapus', $description);
    }

    public function test_csv_template_is_downloadable_with_a_header_and_three_fictional_rows(): void
    {
        $this->admin();
        $response = $this->get(route('admin.model-versions.template'))->assertOk()
            ->assertHeader('content-type', 'text/csv; charset=UTF-8');

        $csv = $response->streamedContent();
        $this->assertStringStartsWith("\xEF\xBB\xBF", $csv, 'the template keeps the same BOM as the other CSV exports');
        $lines = array_values(array_filter(explode("\n", str_replace("\r\n", "\n", trim(substr($csv, 3))))));

        $this->assertSame('text,label', $lines[0]);
        $this->assertCount(4, $lines, 'header plus exactly three example rows');
        foreach (array_slice($lines, 1) as $line) {
            $this->assertMatchesRegularExpression('/,(valid|hoax)$/', $line, 'each example must use a trainable label');
            $this->assertStringNotContainsString('meragukan', $line, 'meragukan is rejected for training');
        }
    }

    public function test_csv_template_route_requires_an_admin(): void
    {
        // A plain web route sends guests to the public login, not the panel login.
        $this->get(route('admin.model-versions.template'))->assertRedirect(route('login'));

        $this->actingAs(User::factory()->create(['is_admin' => false]));
        $this->get(route('admin.model-versions.template'))->assertForbidden();
    }

    public function test_create_form_links_the_template(): void
    {
        $this->admin();

        $this->get(ModelVersionResource::getUrl('create'))->assertOk()
            ->assertSee('Unduh templat CSV')
            ->assertSee(route('admin.model-versions.template'), false);
    }

    public function test_template_matches_the_validator_contract(): void
    {
        $this->admin();
        $csv = $this->get(route('admin.model-versions.template'))->streamedContent();
        $stream = fopen('php://memory', 'r+');
        fwrite($stream, substr($csv, 3));
        rewind($stream);

        $stats = app(BertCsvValidator::class)->validateStream($stream);

        $this->assertSame(3, $stats['total_rows']);
        fclose($stream);
    }

    public function test_activation_logic_is_untouched(): void
    {
        // T3.8 is presentation-only: the service still owns activation.
        $service = app(BertTrainingService::class);
        $this->assertTrue(method_exists($service, 'activateModelVersion'));
        $this->assertTrue(method_exists($service, 'activateBaseline'));

        $this->admin();
        $completed = ModelVersion::factory()->completed()->create(['version_name' => 'v1.9.1']);
        Livewire::test(ViewModelVersion::class, ['record' => $completed->getRouteKey()])
            ->assertActionVisible('activate');
    }

    /** @return array<string, Action|ActionGroup> */
    private function headerActions(): array
    {
        $page = Livewire::test(ListModelVersions::class)->instance();

        return (new \ReflectionMethod($page, 'getHeaderActions'))->invoke($page);
    }

    private function admin(): void
    {
        $this->actingAs(User::factory()->unverified()->create(['is_admin' => true]));
    }
}
